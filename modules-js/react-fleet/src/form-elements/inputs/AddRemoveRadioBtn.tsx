import hash from 'string-hash';

type Props = {
  labels: [string, string] | ['Add', 'Remove'];
  name?: string;
  value: 0 | 1 | true | false;
  id?: string;
  state?: 'default' | 'disabled' | 'focused';
  action?: 'add' | 'remove';
  onClickHandler?: any;
};

export default function AddRemoveRadioBtn(props: Props): JSX.Element {
  const {
    name,
    id = 'id',
    labels,
    state,
    action,
    value,
    onClickHandler,
  } = props;

  const key = id || `id-${hash(id)}`;
  const elemName = name || `AddRemoveBtn--${hash(id)}`;

  return (
    <div
      css={ADDREMOVE_BTN}
      tabIndex={0}
      data-state={state}
      data-action={action}
      id={id}
      onClick={onClickHandler}
      onTouchEnd={() => {
        setTimeout(() => {
          setTimeout(() => {
            onClickHandler();
          }, 500);
        });
      }}
      onKeyUp={e => {
        if (e.keyCode === 13) onClickHandler();
      }}
    >
      <div className="wrapper">
        <label
          htmlFor={key}
          data-content-default={labels[0]}
          data-content-alt={labels[1]}
        />
        <input type="hidden" name={`hidden-${elemName}`} value={`${value}`} />
      </div>
    </div>
  );
}

